#!/usr/bin/env bash
# Copy helper for the justfile push-* recipes.
# Anything that already exists at the destination and differs is backed up to
# ~/.glitcj-env-backups/<timestamp>/ before it is overwritten.
#
#   push.sh file  <src> <dest>
#   push.sh zshrc <repo> <dest>                 # header with repo path + repo .zshrc
#   push.sh dir   <srcdir> <destdir> [seed...]  # seed = relative paths copied only if absent
set -euo pipefail

STAMP="${GLITCJ_PUSH_STAMP:-$(date +%Y%m%d-%H%M%S)}"
BACKUP_ROOT="$HOME/.glitcj-env-backups/$STAMP"

push_file() {
  local src="$1" dest="$2"
  if [ -e "$dest" ]; then
    if cmp -s "$src" "$dest"; then
      echo "  unchanged  $dest"
      return 0
    fi
    local backup="$BACKUP_ROOT/${dest#"$HOME"/}"
    mkdir -p "$(dirname "$backup")"
    cp -p "$dest" "$backup"
    echo "  backup     $dest -> $backup"
  fi
  mkdir -p "$(dirname "$dest")"
  cp "$src" "$dest"
  echo "  pushed     $dest"
}

push_zshrc() {
  local repo="$1" dest="$2"
  ZSHRC_TMP="$(mktemp)"
  trap 'rm -f "$ZSHRC_TMP"' EXIT
  local tmp="$ZSHRC_TMP"
  {
    echo "# >>> generated by 'just push-zshrc' from $repo"
    echo "# >>> edit $repo/.zshrc and push again; changes made here are overwritten"
    echo "export GLITCJ_ENV_REPO=\"$repo\""
    echo
    cat "$repo/.zshrc"
  } > "$tmp"
  push_file "$tmp" "$dest"
}

push_dir() {
  local src="${1%/}" dest="${2%/}"
  shift 2
  local rel seed skip
  while IFS= read -r -d '' path; do
    rel="${path#"$src"/}"
    skip=0
    for seed in "$@"; do
      if [ "$rel" = "$seed" ] && [ -e "$dest/$rel" ]; then
        skip=1
      fi
    done
    if [ "$skip" = 1 ]; then
      echo "  kept       $dest/$rel (seed-only, already exists)"
    else
      push_file "$path" "$dest/$rel"
    fi
  done < <(find "$src" -type f ! -name .DS_Store -print0 | sort -z)
}

cmd="${1:-}"
shift || true
case "$cmd" in
  file)  push_file "$@" ;;
  zshrc) push_zshrc "$@" ;;
  dir)   push_dir "$@" ;;
  *)     echo "usage: push.sh {file|zshrc|dir} ..." >&2; exit 2 ;;
esac
